import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { MongoMemoryServer } from 'mongodb-memory-server';
import request from 'supertest';
import { createApp } from '../src/app.js';
import User from '../src/models/User.js';
let mongo, app, store;
before(async () => {
  mongo = await MongoMemoryServer.create();
  await mongoose.connect(mongo.getUri());
  await User.init();
  const { default: MongoStore } = await import('connect-mongo');
  store = MongoStore.create({ mongoUrl: mongo.getUri() });
  app = createApp({ sessionSecret: 'test-only-secret-at-least-32-characters', sessionStore: store });
});
after(async () => { await store?.close(); await mongoose.disconnect(); await mongo?.stop(); });
test('registration, login, complete post CRUD, ownership, validation and logout', async () => {
  const agent = request.agent(app), other = request.agent(app);
  await request(app).post('/api/posts').send({ title: 'x', content: 'y' }).expect(401);
  await agent.post('/api/users/register').send({ name: 'Om', email: 'bad', password: '123' }).expect(400);
  const user = { name: 'Om', email: 'om@example.test', password: 'TestPassword123!' };
  const registered = await agent.post('/api/users/register').send(user).expect(201);
  assert.equal(registered.body.user.password, undefined);
  const stored = await User.findOne({ email: user.email }).select('+password');
  assert.notEqual(stored.password, user.password);
  await agent.post('/api/users/register').send(user).expect(409);
  await agent.post('/api/users/login').send({ email: user.email, password: 'wrong' }).expect(401);
  await agent.post('/api/users/login').send(user).expect(200);
  await agent.post('/api/posts').send({ title: '', content: 'x' }).expect(400);
  const created = await agent.post('/api/posts').send({ title: 'First post', content: 'Learning Express' }).expect(201);
  const id = created.body.post._id;
  const list = await agent.get('/api/posts').expect(200);
  assert.equal(list.body.total, 1);
  await agent.get('/api/posts?page=0').expect(400);
  await agent.get('/api/posts/invalid').expect(400);
  await agent.get('/api/posts/000000000000000000000000').expect(404);
  assert.equal((await agent.get(`/api/posts/${id}`).expect(200)).body.post.title, 'First post');
  await other.post('/api/users/register').send({ ...user, email: 'other@example.test' }).expect(201);
  await other.post('/api/users/login').send({ ...user, email: 'other@example.test' }).expect(200);
  await other.patch(`/api/posts/${id}`).send({ title: 'stolen' }).expect(403);
  await other.delete(`/api/posts/${id}`).expect(403);
  await agent.patch(`/api/posts/${id}`).send({ author: registered.body.user.id }).expect(400);
  const updated = await agent.patch(`/api/posts/${id}`).send({ title: 'Updated title' }).expect(200);
  assert.equal(updated.body.post.title, 'Updated title');
  await agent.delete(`/api/posts/${id}`).expect(204);
  await agent.get(`/api/posts/${id}`).expect(404);
  await agent.post('/api/users/logout').expect(200);
  await agent.post('/api/posts').send({ title: 'x', content: 'y' }).expect(401);
  await request(app).post('/api/users/login').set('Content-Type', 'application/json').send('{').expect(400);
});
